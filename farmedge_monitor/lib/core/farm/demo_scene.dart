import '../../models/farm_status.dart';
import 'crop_id.dart';
import 'crop_rules.dart';

enum DemoScene { live, dry, happy, rain, storm, fungal }

extension DemoSceneX on DemoScene {
  String get apiName => name.toUpperCase();
}

FarmStatus statusForScene(DemoScene scene, CropId crop, FarmStatus? live) {
  final rules = CropRules.forCrop(crop);
  final base = live ??
      FarmStatus(
        temperature: 27,
        humidity: 70,
        soilMoisture: 55,
        battery: 80,
        pump: false,
        rain: false,
        cropStress: CropStress.low,
        pressure: 1013,
        weatherForecast: 'STABLE',
        weatherSource: 'DEMO',
        batteryHoursRemaining: 20,
        currentDraw: 80,
        lastUpdated: DateTime.now(),
        apiTemperature: 27,
        apiHumidity: 70,
        apiRain: false,
        smartTriggerMode: 'CONFIRMATION',
        alert: 'NONE',
      );

  return switch (scene) {
    DemoScene.live => base,
    DemoScene.dry => FarmStatus(
        temperature: 31,
        humidity: 55,
        soilMoisture: rules.soilDryBelow - 8,
        battery: base.battery,
        pump: false,
        rain: false,
        cropStress: CropStress.medium,
        pressure: 1012,
        weatherForecast: 'STABLE',
        weatherSource: 'DEMO',
        batteryHoursRemaining: base.batteryHoursRemaining,
        currentDraw: 80,
        lastUpdated: DateTime.now(),
        apiTemperature: 31,
        apiHumidity: 55,
        apiRain: false,
        smartTriggerMode: 'CONFIRMATION',
        alert: 'NEEDS_WATER',
      ),
    DemoScene.happy => FarmStatus(
        temperature: 27,
        humidity: 68,
        soilMoisture: (rules.soilHappyLow + rules.soilHappyHigh) / 2,
        battery: base.battery,
        pump: false,
        rain: false,
        cropStress: CropStress.low,
        pressure: 1014,
        weatherForecast: 'STABLE',
        weatherSource: 'DEMO',
        batteryHoursRemaining: base.batteryHoursRemaining,
        currentDraw: 80,
        lastUpdated: DateTime.now(),
        apiTemperature: 27,
        apiHumidity: 68,
        apiRain: false,
        smartTriggerMode: 'CONFIRMATION',
        alert: 'NONE',
      ),
    DemoScene.rain => FarmStatus(
        temperature: 25,
        humidity: 88,
        soilMoisture: rules.soilHappyHigh,
        battery: base.battery,
        pump: false,
        rain: true,
        cropStress: CropStress.low,
        pressure: 1004,
        weatherForecast: 'RAIN_COMING',
        weatherSource: 'DEMO',
        batteryHoursRemaining: base.batteryHoursRemaining,
        currentDraw: 80,
        lastUpdated: DateTime.now(),
        apiTemperature: 25,
        apiHumidity: 88,
        apiRain: true,
        smartTriggerMode: 'CONFIRMATION',
        alert: 'NONE',
      ),
    DemoScene.storm => FarmStatus(
        temperature: 24,
        humidity: 92,
        soilMoisture: rules.soilHappyHigh,
        battery: base.battery,
        pump: false,
        rain: true,
        cropStress: CropStress.low,
        pressure: 988,
        weatherForecast: 'STORM_ALERT',
        weatherSource: 'DEMO',
        batteryHoursRemaining: base.batteryHoursRemaining,
        currentDraw: 80,
        lastUpdated: DateTime.now(),
        apiTemperature: 24,
        apiHumidity: 92,
        apiRain: true,
        smartTriggerMode: 'CONFIRMATION',
        alert: 'NONE',
      ),
    DemoScene.fungal => FarmStatus(
        temperature: (rules.fungalTempMin + rules.fungalTempMax) / 2,
        humidity: rules.fungalHumidityMin + 8,
        soilMoisture: (rules.soilHappyLow + rules.soilHappyHigh) / 2,
        battery: base.battery,
        pump: false,
        rain: false,
        cropStress: CropStress.medium,
        pressure: 1010,
        weatherForecast: 'STABLE',
        weatherSource: 'DEMO',
        batteryHoursRemaining: base.batteryHoursRemaining,
        currentDraw: 80,
        lastUpdated: DateTime.now(),
        apiTemperature: 28,
        apiHumidity: rules.fungalHumidityMin + 8,
        apiRain: false,
        smartTriggerMode: 'CONFIRMATION',
        alert: 'NONE',
      ),
  };
}
